"""Generates each game's index.html, manifest, service worker and PNG icons, plus the
collection-wide service worker that Auto Play uses for offline play.

Run after adding a game or changing any file: bump VERSION first so installed copies update.
    python tools/gen_shells.py
"""
import json
import pathlib
import shutil
import subprocess

VERSION = 7
ROOT = pathlib.Path(__file__).resolve().parent.parent

# slug: (name, background color). Auto Play has its own hand-written page.
GAMES = {
    "pop":    ("Pop!", "#fff0f5"),
    "wipe":   ("Peekaboo", "#7b5cff"),
    "fill":   ("Color In", "#e3f4ff"),
    "sounds": ("Animal Sounds", "#fdf7ff"),
    "push":   ("Push!", "#eefbf3"),
    "crack":  ("Crack!", "#e9f6ff"),
    "water":  ("Fill It Up", "#eaf6ff"),
}
AUTO = ("auto", "Auto Play", "#fdf7ff")

HTML = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<meta name="theme-color" content="{bg}">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<title>{name}</title>
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icons/icon-192.png">
<link rel="apple-touch-icon" href="icons/icon-192.png">
<style>
  html, body {{
    margin: 0; height: 100%; overflow: hidden;
    background: {bg};
    overscroll-behavior: none;
    touch-action: none;
    user-select: none; -webkit-user-select: none;
    -webkit-touch-callout: none;
    -webkit-tap-highlight-color: transparent;
  }}
  canvas {{ position: fixed; inset: 0; width: 100%; height: 100%; display: block; touch-action: none; }}
</style>
</head>
<body>
<canvas id="c"></canvas>
<script src="../shared/toddler.js"></script>
<script src="game.js"></script>
</body>
</html>
"""

SW = """// Generated by tools/gen_shells.py. Bump VERSION there when any file changes.
const VERSION = {version};
const CACHE = '{name}-v' + VERSION;
const ASSETS = {assets};

self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)));
  self.skipWaiting();
}});

self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys =>
    Promise.all(keys.filter(k => k.startsWith('{name}-') && k !== CACHE).map(k => caches.delete(k)))));
  self.clients.claim();
}});

self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(r => r || fetch(e.request)));
}});
"""

ICONS = ["icons/icon-192.png", "icons/icon-512.png", "icons/maskable-512.png"]


def render(svg, out, size):
    if out.exists() and out.stat().st_mtime >= svg.stat().st_mtime:
        return  # up to date; re-rendering only churns the PNG bytes
    subprocess.run(["magick", "-background", "none", "-density", "384", str(svg),
                    "-resize", f"{size}x{size}", str(out)], check=True)


def icons(d):
    icons_dir = d / "icons"
    render(icons_dir / "icon.svg", icons_dir / "icon-512.png", 512)
    render(icons_dir / "icon.svg", icons_dir / "icon-192.png", 192)
    maskable = icons_dir / "maskable.svg"
    if maskable.exists():
        render(maskable, icons_dir / "maskable-512.png", 512)
    elif not (icons_dir / "maskable-512.png").exists() or \
            (icons_dir / "maskable-512.png").stat().st_mtime < (icons_dir / "icon-512.png").stat().st_mtime:
        # Full-bleed icons keep their content inside the maskable safe zone already.
        shutil.copy(icons_dir / "icon-512.png", icons_dir / "maskable-512.png")


def manifest(d, slug, name, bg):
    data = {
        "id": f"toddler-games-{slug}",
        "name": name,
        "short_name": name,
        "start_url": "./",
        "scope": "./",
        "display": "fullscreen",
        "display_override": ["fullscreen"],
        "orientation": "any",
        "background_color": bg,
        "theme_color": bg,
        "icons": [
            {"src": ICONS[0], "sizes": "192x192", "type": "image/png", "purpose": "any"},
            {"src": ICONS[1], "sizes": "512x512", "type": "image/png", "purpose": "any"},
            {"src": ICONS[2], "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        ],
    }
    (d / "manifest.webmanifest").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def write_sw(path, name, assets):
    path.write_text(SW.format(version=VERSION, name=name, assets=json.dumps(assets, indent=2)), encoding="utf-8")


everything = ["./", "./index.html", "./shared/toddler.js"]

for slug, (name, bg) in GAMES.items():
    d = ROOT / slug
    (d / "index.html").write_text(HTML.format(name=name, bg=bg), encoding="utf-8")
    files = ["./index.html", "./game.js", "./manifest.webmanifest"] + [f"./{p}" for p in ICONS]
    write_sw(d / "sw.js", slug, ["./"] + files + ["../shared/toddler.js"])
    manifest(d, slug, name, bg)
    icons(d)
    everything += [f"./{slug}/"] + [f"./{slug}/{f[2:]}" for f in files]
    print("ok", slug)

slug, name, bg = AUTO
d = ROOT / slug
manifest(d, slug, name, bg)
icons(d)
everything += [f"./{slug}/", f"./{slug}/index.html", f"./{slug}/auto.js", f"./{slug}/manifest.webmanifest"] + \
    [f"./{slug}/{p}" for p in ICONS]
write_sw(ROOT / "sw.js", "all", everything)
print("ok", slug, "+ root sw.js with", len(everything), "files")
